-- Phase 5 — close the catalog gaps of the imported ledger
--
-- The sales ledger references 25 SKUs that the price sheets do not contain
-- (756 sales). Those sales had no product, so the
-- product column was empty in Vendas, Painel, Clientes and Recebíveis.
--
-- This migration:
--   1. creates the missing products from the workbook (Lançamento de Venda,
--      columns E/M/N/O) as inactive, price-less items — they are history, not
--      sellable stock;
--   2. links the affected sales through sales.legacy_row;
--   3. backfills sales.product_name_raw from the catalog so every sale has a
--      readable product.
--
-- The names and PVs come from the workbook, so nothing is invented. Three old
-- SKUs may be the same products as current ones and deserve a look:
--   #0146 Shake Cookies          -> #295K Shake Cookies & Cream 550g
--   #1522 / #174K Shake Banana   -> #326K Shake Banana Caramelizada 550g
--   #0009 (1 sale) Shake Doce de Leite -> #0940 Shake Doce de Leite 550g
-- ============================================================================

